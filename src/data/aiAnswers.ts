export const aiAnswers: Record<string, Record<string, AiAnswer>> = Object.fromEntries(
  checks.flatMap((c) => c.rows).map((r) => {
    const own: Record<string, AiAnswer> = {};
    if (r.sources.length) own["source"] = sourceAnswer(r);
    Object.assign(own, manual[r.id] ?? {});
    return [r.id, own];
  }),
);

export const QUESTIONS: { id: QuestionId; label: string; applies: (r: Row) => boolean }[] = [
  { id: "why", label: "Почему расхождение?", applies: (r) => r.status === "discrepancy" },
  { id: "source", label: "Откуда ожидаемое значение?", applies: (r) => r.sources.length > 0 },
  { id: "need", label: "Что нужно, чтобы проверить?", applies: (r) => r.status === "unverified" },
  { id: "excluded", label: "Почему подтверждено, если в папке есть дубль?", applies: (r) => r.status === "verified" },
  { id: "draft", label: "Черновик пояснения", applies: (r) => r.status === "discrepancy" || r.status === "unverified" },
];
