import { formatMoney } from "@/components/money-format";
import { checks, type Row } from "./mock";

export type QuestionId = "why" | "source" | "need" | "draft" | "excluded";
export type AiRef = { docId: string; page: number; label: string };
export type AiAnswer = { text: string; refs: AiRef[]; hypothesis?: boolean };

const m = formatMoney;
const docs = new Map(checks.flatMap((c) => c.docs.map((d) => [d.id, d] as const)));
const ref = (docId: string, page = 1): AiRef => {
  const d = docs.get(docId);
  return { docId, page, label: `${d?.title ?? docId}, стр. ${page}` };
};

/** «Откуда ожидаемое значение?» — собирается только из полей строки и документов моков. */
function sourceAnswer(r: Row): AiAnswer {
  const parts = r.sources.map((s) => `${docs.get(s.docId)?.title ?? s.docId} — ${s.amount ? `${m(s.amount)} ₽` : "сумма не прочитана"}`);
  const head = r.expected !== null
    ? `Значение «по документам» ${m(r.expected)} ₽ получено правилом ${r.ruleId}`
    : `Значение «по документам» не определено правилом ${r.ruleId}: ${r.reason.charAt(0).toLowerCase()}${r.reason.slice(1)}`;
  return { text: `${head}. Использованы документы: ${parts.join("; ")}.`, refs: r.sources.map((s) => ref(s.docId, s.page)) };
}

